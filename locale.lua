function TuningLocale()
    return Config.Locale == 'en' and 'en' or 'de'
end

function TuningText(text, ...)
    local translated = TuningLocale() == 'en' and english[text] or text
    if select('#', ...) > 0 then return translated:format(...) end
    return translated
end

function TuningInterface()
    local language = TuningLocale() == 'en' and 2 or 1
    local strings = {}
    for key, values in pairs(interface) do strings[key] = values[language] end
    return strings
end